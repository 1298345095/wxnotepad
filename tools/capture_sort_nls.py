"""Capture the Windows user-default NLS weights used by StrCmpLogicalW.

Run on the Windows reference machine; the generated adapter keeps native Linux
sorting independent of the host's different Unicode collation data.
"""
import ctypes
from ctypes import wintypes
import platform
import struct
import zlib
from pathlib import Path


def capture(destination: Path) -> None:
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    mapping = kernel.LCMapStringEx
    mapping.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.LPCWSTR, ctypes.c_int,
                        ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_ssize_t]
    mapping.restype = ctypes.c_int
    locale = ctypes.create_unicode_buffer(85)
    kernel.GetUserDefaultLocaleName(locale, len(locale))
    output = ctypes.create_string_buffer(256)
    records = []
    previous = None
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        text = chr(codepoint)
        length = mapping(None, 0x401, text, len(text.encode("utf-16-le")) // 2,
                         output, len(output), None, None, 0)
        if not length:
            raise ctypes.WinError(ctypes.get_last_error())
        key = output.raw[:length - 1]
        primary_length = key.index(1)
        primary = int.from_bytes(key[:primary_length], "big")
        tail = key[primary_length:]
        if previous is not None:
            first, last, first_key, stride, old_primary, old_tail, old_length = previous
            delta = primary - old_primary
            if codepoint == last + 1 and tail == old_tail and primary_length == old_length and primary_length <= 8 and (
                stride is None or stride == delta
            ):
                previous = (first, codepoint, first_key, delta, primary, tail, primary_length)
                continue
            records.append(previous)
        previous = (codepoint, codepoint, key, None, primary, tail, primary_length)
    records.append(previous)
    data = bytearray()
    for first, last, key, stride, _, _, primary_length in records:
        data.extend(struct.pack("<IIqBB", first, last, stride or 0, primary_length, len(key)))
        data.extend(key)
    packed = zlib.compress(data, 9)
    with destination.open("w", encoding="utf-8", newline="\n") as file:
        file.write("// Generated by tools/capture_sort_nls.py; do not edit.\n")
        file.write(f"// {platform.platform()}, user locale {locale.value}; LCMapStringEx(LCMAP_SORTKEY | NORM_IGNORECASE).\n")
        file.write("#pragma once\n#include <cstddef>\n\nnamespace OriginalNls {\n")
        file.write(f"inline constexpr size_t sortDataSize = {len(data)};\n")
        file.write("inline constexpr char sortData[] =\n")
        for start in range(0, len(packed), 32):
            literal = "".join(f"\\x{byte:02x}" for byte in packed[start:start + 32])
            file.write(f'    "{literal}"\n')
        file.write(";\n}\n")
    print(f"Captured {len(records)} ranges, {len(packed)} compressed bytes, {destination.stat().st_size} source bytes, locale {locale.value}")


if __name__ == "__main__":
    capture(Path(__file__).resolve().parents[1] / "src/editor/platform/generated/sort_nls_data.h")
