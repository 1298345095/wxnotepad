"""Retain pinned filename precedence without compiling additional lexers."""
import argparse
from pathlib import Path
import re
import subprocess

from scheme_data import REVISION, read_pinned


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    styles = read_pinned(args.source, "src/Styles.cpp").decode("utf-8-sig")
    order = re.search(r"pLexArray\[\]\s*=\s*\{(.*?)\n\};", styles, re.S)[1]
    names = re.findall(r"&(lex\w+)", order)
    files = subprocess.check_output(["git", "-C", str(args.source), "ls-tree", "-r", "--name-only",
                                     REVISION, "src/EditLexers"], text=True).splitlines()
    lexers = {}
    for file in files:
        if not file.endswith(".cpp"):
            continue
        text = read_pinned(args.source, file).decode("utf-8-sig")
        for name, body in re.findall(r"EDITLEXER\s+(lex\w+)\s*=\s*\{(.*?)\n\};", text, re.S):
            extension = re.search(r'EDITLEXER_(?:HOLE|TEXT)\([^\n]*\),\s*L"([^"]*)"', body)
            if extension:
                lexers[name] = [item.strip().lower() for item in extension[1].split(";") if item.strip()]
    associations = {}
    for name in names:
        for extension in lexers.get(name, []):
            associations.setdefault(extension, name)
    blocked = sorted(extension for extension, name in associations.items() if name != "lexConfig")
    lines = ["// Generated by tools/update_detection_extensions.py; do not edit.",
             f"// Notepad4 {REVISION}, src/Styles.cpp and src/EditLexers/stl*.cpp.",
             "// Copyright and BSD 3-Clause license: licenses/Notepad4.txt.",
             "// Config associations permit shebang sniffing in the original; all others take precedence.",
             "constexpr std::string_view originalAssociatedExtensions ="]
    for offset in range(0, len(blocked), 12):
        lines.append('    "' + ';'.join(blocked[offset:offset + 12]) + ';"')
    lines[-1] += ";"
    config = sorted(extension for extension, name in associations.items() if name == "lexConfig")
    lines.append('constexpr std::string_view originalConfigExtensions = "' + ';'.join(config) + ';";')
    target = Path(__file__).resolve().parents[1] / "src/syntax/generated/detection_extensions.h"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
