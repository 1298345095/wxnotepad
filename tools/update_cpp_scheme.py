"""Reproduce selected C++ syntax data from the pinned Notepad4 checkout (offline)."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess

REVISION = "89b8b36e0ee2c23f73be922315f17261ccfbbe1a"
ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    args = parser.parse_args()
    data = subprocess.check_output(["git", "-C", str(args.source), "show",
                                    f"{REVISION}:src/EditLexers/stlCPP.cpp"])
    text = data.decode("utf-8").replace("\r\n", "\n")
    keywords = text.split("static const char * const Keywords_CPP[] = {", 1)[1].split(", // 13 C Function", 1)[0]
    styles = text.split("static const EDITSTYLE Styles_CPP[] = {", 1)[1].split("};", 1)[0]
    output = ["// Generated by tools/update_cpp_scheme.py; do not edit.",
              f"// Notepad4 {REVISION}, src/EditLexers/stlCPP.cpp",
              f"// Original file SHA-256: {hashlib.sha256(data).hexdigest()}",
              "// Copyright and BSD 3-Clause license: licenses/Notepad4.txt.",
              "// Lists 13-15 are completion-only (KeywordAttr_NoLexer), so omitted.",
              "// No lexer-consumed attributes: NoAutoComp (2,3,11,12) is app-only.",
              "// clang-format off",
              "constexpr const char* cppKeywords[] = {" + keywords + "};", "",
              "constexpr SyntaxStyle cppStyles[] = {"]
    for line in styles.splitlines():
        if 'L"' not in line:
            continue
        ids = re.findall(r"SCE_C_\w+", line)
        value = re.search(r'L"([^"]+)"', line)[1]
        fore = re.search(r"fore:#([0-9A-Fa-f]{6})", value)
        back = re.search(r"back:#([0-9A-Fa-f]{6})", value)
        for style in ids:
            output.append(f"    {{{style}, 0x{fore[1] if fore else '000000'}, "
                          f"0x{back[1] if back else 'FFFFFF'}, {'true' if 'bold' in value else 'false'}}},")
    output.append("};\n// clang-format on\n")
    (ROOT / "src/cpp_scheme_data.h").write_text("\n".join(output), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
