"""Small shared helpers for the pinned syntax-data generators."""
import hashlib
import re
import subprocess

REVISION = "89b8b36e0ee2c23f73be922315f17261ccfbbe1a"


def read_pinned(source, path):
    return subprocess.check_output(["git", "-C", str(source), "show", f"{REVISION}:{path}"])


def provenance(generator, path, data):
    return [f"// Generated by tools/{generator}; do not edit.",
            f"// Notepad4 {REVISION}, {path}",
            f"// Original file SHA-256: {hashlib.sha256(data).hexdigest()}",
            "// Copyright and BSD 3-Clause license: licenses/Notepad4.txt."]


def _style_line_initializers(line, prefix, *, eol_filled, offset):
    value = re.search(r'L"([^"]*)"', line)[1]
    fore = re.search(r"fore:#([0-9A-Fa-f]{6})", value)
    back = re.search(r"back:#([0-9A-Fa-f]{6})", value)
    extra = (f", {str('italic' in value).lower()}, {str('eolfilled' in value).lower()}"
             if eol_filled else "")
    if any(attribute in value for attribute in ('underline', 'strike', 'overline')):
        extra += ', ' + ', '.join(str(attribute in value).lower()
                                 for attribute in ('underline', 'strike', 'overline'))
    output = []
    for style in re.findall(rf"{prefix}\w+", line):
        if offset:
            style = f"{offset}({style})"
        output.append(f"    {{{style}, 0x{fore[1] if fore else '000000'}, "
                      f"0x{back[1] if back else 'FFFFFF'}, {'true' if 'bold' in value else 'false'}{extra}}},")
    return output


def style_initializers(styles, prefix, *, eol_filled=False, offset=""):
    output = []
    for line in styles.splitlines():
        if 'L"' not in line:
            continue
        output.extend(_style_line_initializers(line, prefix, eol_filled=eol_filled, offset=offset))
    return output


KEYWORD_ATTRIBUTES = {'Default': 0, 'MakeLower': 1, 'PreSorted': 2, 'NoLexer': 4, 'NoAutoComp': 8}
LEXER_ATTRIBUTES = {name: 1 << bit for bit, name in enumerate((
    'TabAsSpaces', 'NoGlobalTabSettings', 'NoLineComment', 'NoBlockComment',
    'IndentBasedFolding', 'IndentLookForward', 'PrintfFormatSpecifier', 'AngleBracketGeneric',
    'CppPreprocessor', 'CharacterPrefix', 'EscapePunctuation', 'PlainTextFile', 'CodePretty'))}
LEXER_ATTRIBUTES['Default'] = 0


def _attributes(expression, prefix, values):
    result = 0
    for token in expression.split('|'):
        name = token.strip().removeprefix(prefix)
        # Unknown original attributes must be adapted explicitly, never dropped.
        result |= values[name]
    return result


def original_scheme(data, symbol):
    """Extract the original generated table shape; not a general C++ parser."""
    text = data.decode('utf-8').replace('\r\n', '\n')
    keywords = text.split(f'static const char * const Keywords_{symbol}[] = {{', 1)[1].split('};', 1)[0]
    styles = text.split(f'static const EDITSTYLE Styles_{symbol}[] = {{', 1)[1].split('};', 1)[0]
    settings = text.split('//Settings++Autogenerated', 1)[1].split('\n', 1)[1].split('//Settings--Autogenerated', 1)[0]
    settings = re.sub(r'//[^\n]*', '', settings)
    before, remainder = re.split(r',\s*(?=KeywordAttr)', settings, maxsplit=1)
    last_attribute = remainder.rfind(')') + 1
    attributes = remainder[:last_attribute]
    after = remainder[last_attribute:].lstrip().removeprefix(',')
    # The generated EDITLEXER initializer has 13 scalar fields before keywordAttr.
    fields = [value.strip() for value in before.split(',')]
    if len(fields) != 13:
        raise ValueError(f'{symbol}: expected 13 original settings fields, got {len(fields)}')
    fields[0] = str(_attributes(fields[0], 'LexerAttr_', LEXER_ATTRIBUTES))
    fields = [re.sub(r'(?:TAB|INDENT)_WIDTH_(\d+)', r'\1', value) for value in fields]
    tail = [value.strip() for value in after.split(',') if value.strip()]
    if len(tail) != 3:
        raise ValueError(f'{symbol}: expected comment/string style metadata')
    # Commas occur only between entries, outside string literals and comments.
    literals = re.sub(r'//[^\n]*', '', keywords)
    # Count lists from separators after removing string contents.
    count = len(re.sub(r'"(?:[^"\\]|\\.)*"', '', literals).split(','))
    flags = [0] * count
    for index, expression in re.findall(r'KeywordAttr(?:32|64)\((\d+),\s*([^)]*)\)', attributes):
        flags[int(index)] = _attributes(expression, 'KeywordAttr_', KEYWORD_ATTRIBUTES)
    extensions = re.search(r'\n\s*L"([^"\n]+)"\s*,\s*Keywords_' + symbol, text)[1]
    title = re.search(r'EDITLEXER_HOLE\(L"([^"]+)"', text)[1]
    return keywords, flags, styles, fields + tail, [ext.strip() for ext in extensions.split(';')], title


def generate_scheme(data, filename, symbol, name, *, include_extensions=True):
    keywords, flags, styles, metadata, extensions, title = original_scheme(data, symbol)
    output = provenance('update_schemes.py', f'src/EditLexers/stl{filename}.cpp', data)
    output += ['// Full original groups and attributes, including completion-only lists.',
               '// clang-format off', f'constexpr const char* {name}Keywords[] = {{' + keywords + '};',
               f'constexpr SyntaxKeywords {name}Lists[] = {{']
    output += [f'    {{{name}Keywords[{index}] ? {name}Keywords[{index}] : "", {flag}U << 8U}},'
               for index, flag in enumerate(flags)]
    output += ['};', f'constexpr SyntaxStyle {name}Styles[] = {{',
               *style_initializers(styles, 'SCE_', eol_filled=True), '};',
               f'constexpr SyntaxOriginalMetadata {name}Original = {{' + ', '.join(metadata) + '};',
               f'constexpr const char* {name}SettingsSection = "{title}";']
    if include_extensions:
        output += [f'constexpr const char* {name}Extensions[] = {{' +
                   ', '.join(f'"{ext}"' for ext in extensions) + '};']
    return '\n'.join(output + ['// clang-format on', ''])
