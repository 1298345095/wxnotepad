#!/usr/bin/env python3
"""Maintain standard gettext catalogs and generated release-language metadata."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def metadata(root):
    data = json.loads((root / 'po/languages.json').read_text(encoding='utf-8'))
    if not re.fullmatch(r'[A-Za-z0-9_-]+', data['domain']):
        raise ValueError('Invalid catalog domain')
    codes, identifiers = set(), set()
    for language in data['languages']:
        code, identifier = language['code'], language['lang_id']
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', code) or code in codes:
            raise ValueError('Invalid or duplicate language code: ' + code)
        if not isinstance(identifier, int) or not 0 < identifier <= 65535 or identifier in identifiers:
            raise ValueError('Invalid or duplicate language LANGID')
        if not language['name']:
            raise ValueError('Missing native language name')
        codes.add(code)
        identifiers.add(identifier)
    if data['source_language'] not in codes:
        raise ValueError('Source language must be a release language')
    return data


def write_changed(path, text):
    if not path.exists() or path.read_bytes() != text.encode('utf-8'):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode('utf-8'))


def header(data, output):
    rows = []
    for language in data['languages']:
        translated = str(language['code'] != data['source_language']).lower()
        rows.append('    {' + str(language['lang_id']) + ', ' +
                    json.dumps(language['code']) + ', ' + json.dumps(language['name'], ensure_ascii=False) +
                    ', ' + translated + '},')
    write_changed(output, '// Generated by tools/localization.py; edit po/languages.json.\n'
                  '#pragma once\n\n#include <array>\n#include <cstdint>\n#include <string_view>\n\n'
                  'namespace AppLocalization {\n'
                  'struct LanguageDefinition {\n    uint16_t langId;\n    std::string_view code;\n'
                  '    std::string_view nativeName;\n    bool hasCatalog;\n};\n'
                  'inline constexpr std::string_view CatalogDomain = ' + json.dumps(data['domain']) + ';\n'
                  'inline constexpr std::array<LanguageDefinition, ' + str(len(rows)) +
                  '> LanguageDefinitions{{\n' + '\n'.join(rows) + '\n}};\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT, help='Source root (for standalone build checks)')
    commands = parser.add_subparsers(dest='command', required=True)
    generate = commands.add_parser('header')
    generate.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    data = metadata(args.root)
    header(data, args.output)


if __name__ == '__main__':
    main()
