"""Capture Windows GetDlgItemInt digits; format the generated header with clang-format 23.1.2."""
import ctypes as c
from ctypes import wintypes as w
from pathlib import Path
import sys


def main():
    print(f"Reference host: {sys.getwindowsversion()}")
    user = c.WinDLL("user32", use_last_error=True)
    user.CreateWindowExW.argtypes = [w.DWORD, w.LPCWSTR, w.LPCWSTR, w.DWORD, c.c_int, c.c_int,
                                     c.c_int, c.c_int, w.HWND, w.HMENU, w.HINSTANCE, c.c_void_p]
    user.CreateWindowExW.restype = w.HWND
    user.SetWindowTextW.argtypes = [w.HWND, w.LPCWSTR]
    user.GetDlgItemInt.argtypes = [w.HWND, c.c_int, c.POINTER(w.BOOL), w.BOOL]
    user.GetDlgItemInt.restype = w.UINT
    user.DestroyWindow.argtypes = [w.HWND]
    parent = user.CreateWindowExW(0, "STATIC", "", 0, 0, 0, 0, 0, None, None, None, None)
    edit = user.CreateWindowExW(0, "EDIT", "", 0x40000000, 0, 0, 0, 0, parent, 101, None, None)
    if not parent or not edit:
        raise c.WinError(c.get_last_error())
    ranges = []
    count = 0
    try:
        translated = w.BOOL()
        for point in range(1, 0x110000):
            if 0xD800 <= point <= 0xDFFF:
                continue
            if not user.SetWindowTextW(edit, chr(point)):
                raise c.WinError(c.get_last_error())
            digit = user.GetDlgItemInt(parent, 101, c.byref(translated), False)
            if translated.value and digit < 10:
                count += 1
                zero = point - digit
                if ranges and ranges[-1][1] + 1 == point and ranges[-1][2] == zero:
                    ranges[-1][1] = point
                else:
                    ranges.append([point, point, zero])
    finally:
        user.DestroyWindow(parent)
    rows = ["// Generated by tools/capture_column_wrap_digits.py using Windows GetDlgItemInt.",
            "// Only independently accepted single Unicode digits are represented.",
            "#pragma once", "", "#include <cstdint>", "", "struct ColumnWrapDigitRange {",
            "    char32_t first;", "    char32_t last;", "    char32_t zero;", "};", "",
            "inline constexpr ColumnWrapDigitRange ColumnWrapDigitRanges[] = {"]
    rows.extend(f"    {{0x{first:X}, 0x{last:X}, 0x{zero:X}}}," for first, last, zero in ranges)
    rows.extend(["};", ""])
    output = Path(sys.argv[1])
    output.write_text("\n".join(rows), encoding="utf-8", newline="\n")
    print(f"Captured {count} accepted digits in {len(ranges)} ranges to {output}")


if __name__ == "__main__":
    main()
