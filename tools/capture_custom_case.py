"""Capture Windows NLS behavior used by Notepad4 89b8b36 EditMapTextCase.

Run on the Windows reference host. Generated ranges preserve UTF-16 character
operations for Invert/Sentence and NLS linguistic mapping for Title/Sentence.
"""
import ctypes
import platform
from pathlib import Path

kernel = ctypes.windll.kernel32
user = ctypes.windll.user32
kernel.LCMapStringEx.argtypes = [ctypes.c_wchar_p, ctypes.c_ulong, ctypes.c_wchar_p,
                              ctypes.c_int, ctypes.c_wchar_p, ctypes.c_int,
                              ctypes.c_void_p, ctypes.c_void_p, ctypes.c_longlong]
for name in ("IsCharUpperW", "IsCharLowerW", "IsCharAlphaNumericW"):
    getattr(user, name).argtypes = [ctypes.c_wchar]
for name in ("CharUpperW", "CharLowerW"):
    getattr(user, name).argtypes = [ctypes.c_void_p]
    getattr(user, name).restype = ctypes.c_void_p


def mapping(text, flags, linguistic=True):
    buffer = ctypes.create_unicode_buffer(len(text) * 4 + 8)
    length = len(text.encode("utf-16-le", errors="surrogatepass")) // 2
    count = kernel.LCMapStringEx(None, (0x1000000 if linguistic else 0) | flags, text, length,
                               buffer, len(buffer), None, None, 0)
    assert count
    return buffer[:count].encode("utf-16-le", errors="surrogatepass").decode("utf-16-le", errors="surrogatepass")


def ranges(values):
    start = 0
    for index in range(1, len(values) + 1):
        if index == len(values) or values[index] != values[start]:
            if values[start]:
                yield start, index - 1, values[start]
            start = index


def utf16_character_properties(value):
    if value >= 0x10000:
        return 0, 0
    char = chr(value)
    invert = value
    if user.IsCharUpperW(char):
        invert = user.CharLowerW(value)
    elif user.IsCharLowerW(char):
        invert = user.CharUpperW(value)
    sentence = int(bool(user.IsCharAlphaNumericW(char)))
    sentence |= int(bool(user.IsCharLowerW(char))) << 1
    return invert - value, sentence


def capture_character(value):
    char = chr(value)
    lower = mapping(char, 0x100)
    title = mapping(char, 0x300)
    upper = mapping(char, 0x200, linguistic=False)
    assert len(upper) == len(lower) == len(title) == 1, (value, upper, lower, title)
    invert, sentence = utf16_character_properties(value)
    # Bit 0: following character starts a word when this starts a word.
    # Bit 1: following character starts a word when this continues a word.
    title_state = ((mapping(char + "b", 0x300)[-1] == "B") |
                   ((mapping("a" + char + "b", 0x300)[-1] == "B") << 1))
    # Title reuses Upper, including a negative delta when Title leaves a
    # character unchanged that Upper maps. Both values come from Windows NLS.
    return ord(upper) - value, ord(lower) - value, ord(title) - ord(upper), invert, sentence, title_state


def capture_properties():
    properties = {name: [] for name in ("Upper", "Lower", "TitleDelta", "Invert", "Sentence", "TitleState")}
    for value in range(0x110000):
        values = (0,) * len(properties)
        if not 0xD800 <= value <= 0xDFFF:
            values = capture_character(value)
        for target, captured in zip(properties.values(), values):
            target.append(captured)
    return properties


def write_properties(output, properties):
    locale = ctypes.create_unicode_buffer(85)
    kernel.GetUserDefaultLocaleName(locale, len(locale))
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("// Generated by tools/capture_custom_case.py on Windows.\n"
                     f"// Reference: {platform.platform()}, locale {locale.value}.\n"
                     "// Notepad4 89b8b36: Windows NLS linguistic casing, CharUpper/Lower, title-word transitions.\n"
                     "#pragma once\n#include <array>\n#include <cstdint>\nnamespace WindowsCaseData {\n"
                     "struct Range { uint32_t first; uint32_t last; int32_t value; };\n")
        for name, values in properties.items():
            captured_ranges = list(ranges(values))
            stream.write(f"inline constexpr std::array<Range, {len(captured_ranges)}> {name}{{{{\n")
            for first, last, value in captured_ranges:
                stream.write(f"    {{0x{first:x}, 0x{last:x}, {value}}},\n")
            stream.write("}};\n")
        stream.write("}\n")


def main():
    output = Path(__file__).parents[1] / "src/editor/platform/windows_case_data.h"
    write_properties(output, capture_properties())


if __name__ == "__main__":
    main()
