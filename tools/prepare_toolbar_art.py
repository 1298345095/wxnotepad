"""Embed the pinned Notepad4 toolbar's independently drawn DPI resources.

Usage: python tools/prepare_toolbar_art.py <Notepad4 source checkout>
Requires Pillow. The existing Notepad4 BSD notice covers these original assets.
"""
import io
from pathlib import Path
import sys
import subprocess
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
lines = ['// Generated by tools/prepare_toolbar_art.py from Notepad4 89b8b36.',
         '// Original artwork: see licenses/Notepad4.txt.', '#pragma once',
         '#include <wx/bitmap.h>', '#include <wx/bmpbndl.h>', 'namespace ToolbarArt {']
for size in (16, 24, 32, 40, 48):
    original = subprocess.check_output(['git', '-C', str(source), 'show',
                                        f'89b8b36e0ee2c23f73be922315f17261ccfbbe1a:res/Toolbar{size}.bmp'])
    image = Image.open(io.BytesIO(original)).convert('RGBA')
    # Original CreateBars uses ImageList_AddMasked(..., CLR_DEFAULT): top-left key.
    key = image.getpixel((0, 0))[:3]
    image.putdata([(*pixel[:3], 0 if pixel[:3] == key else 255) for pixel in image.getdata()])
    output = io.BytesIO()
    image.save(output, format='PNG')
    lines.append(f'inline constexpr unsigned char Strip{size}[] = {{')
    data = output.getvalue()
    for offset in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(value) for value in data[offset:offset + 24]) + ',')
    lines.append('};')
lines += ['inline wxBitmapBundle Icon(int index) {', '    wxVector<wxBitmap> icons;']
for size in (16, 24, 32, 40, 48):
    lines.append(f'    icons.push_back(wxBitmap::NewFromPNGData(Strip{size}, sizeof(Strip{size})).GetSubBitmap(wxRect(index * {size}, 0, {size}, {size})));')
lines += ['    return wxBitmapBundle::FromBitmaps(icons);', '}', '} // namespace ToolbarArt', '']
(root / 'src/app/toolbar_art.h').write_text('\n'.join(lines), encoding='utf-8')

subprocess.run(['clang-format', '-i', str(root / 'src/app/toolbar_art.h')], check=True)
