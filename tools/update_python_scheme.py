"""Reproduce Python lexer-consumed syntax data from the pinned checkout (offline)."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess

REVISION = "89b8b36e0ee2c23f73be922315f17261ccfbbe1a"
ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    args = parser.parse_args()
    data = subprocess.check_output(["git", "-C", str(args.source), "show",
                                    f"{REVISION}:src/EditLexers/stlPython.cpp"])
    text = data.decode("utf-8").replace("\r\n", "\n")
    keywords = text.split("static const char * const Keywords_Python[] = {", 1)[1].split(", // 7 decorator", 1)[0]
    styles = text.split("static const EDITSTYLE Styles_Python[] = {", 1)[1].split("};", 1)[0]
    output = ["// Generated by tools/update_python_scheme.py; do not edit.",
              f"// Notepad4 {REVISION}, src/EditLexers/stlPython.cpp",
              f"// Original file SHA-256: {hashlib.sha256(data).hexdigest()}",
              "// Copyright and BSD 3-Clause license: licenses/Notepad4.txt.",
              "// Lists 7-12 are completion-only (KeywordAttr_NoLexer), so omitted.",
              "// Lists 0-6 retain KeywordAttr_PreSorted (2).",
              "// clang-format off",
              "constexpr const char* pythonKeywords[] = {" + keywords + "};", "",
              "constexpr SyntaxStyle pythonStyles[] = {"]
    for line in styles.splitlines():
        if 'L"' not in line:
            continue
        value = re.search(r'L"([^"]+)"', line)[1]
        fore = re.search(r"fore:#([0-9A-Fa-f]{6})", value)
        back = re.search(r"back:#([0-9A-Fa-f]{6})", value)
        for style in re.findall(r"SCE_PY_\w+", line):
            output.append(f"    {{{style}, 0x{fore[1] if fore else '000000'}, "
                          f"0x{back[1] if back else 'FFFFFF'}, {'true' if 'bold' in value else 'false'}}},")
    output.append("};\n// clang-format on\n")
    (ROOT / "src/python_scheme_data.h").write_text("\n".join(output), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
